"""Collect the imports of a staged Python tree so PyInstaller can see them.

PyInstaller's analysis starts at the entry script and follows ``import``
statements statically. That misses two common setups:

* scripts executed with ``runpy`` (a launcher loads them by path), and
* imports resolved at runtime by a plugin mechanism.

Both fail the same way: the app runs fine from source, then the frozen build
dies with ``ModuleNotFoundError`` on first use. The usual fix is a hand-written
list of hidden imports — which drifts the moment somebody adds an import.

This module replaces the list with a scan: parse every ``.py`` file under a
root, collect ``import x`` and ``from x import y``, drop local modules and
anything you asked to exclude, and emit a generated module that imports the
rest. PyInstaller sees the generated module because it is imported by the entry
script; the imports are real, so nothing has to be kept in sync by hand.

    python -m pyi_deps --root src/runtime --out build/_deps.py

A subtlety worth the code: ``from Crypto.Cipher import AES`` names a module,
not an attribute, and PyInstaller will bundle ``Crypto.Cipher`` but not
``AES``. The scanner checks each imported name with :func:`importlib.util.find_spec`
and adds ``Crypto.Cipher.AES`` when it resolves.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import sys
from pathlib import Path
from typing import Iterable, Sequence

__all__ = ["scan", "render", "main"]

HEADER = (
    "# Generated by pyi_deps -- do not edit.\n"
    "# Imported by the entry script so PyInstaller's static analysis sees these.\n"
)


def _submodule_exists(name: str) -> bool:
    try:
        return importlib.util.find_spec(name) is not None
    except (ImportError, AttributeError, ValueError):
        return False


def _is_excluded(name: str, prefixes: Sequence[str]) -> bool:
    return any(name == p or name.startswith(p + ".") for p in prefixes)


def scan(root: str | Path, *, local_modules: Iterable[str] = (),
         exclude_prefixes: Iterable[str] = (), resolve_submodules: bool = True) -> list[str]:
    """Return every third-party import found under *root*, sorted and unique.

    ``local_modules`` are top-level names that live next to the scanned files and
    are resolved by the runtime itself; excluding them keeps the generated module
    importable outside the frozen build.

    ``resolve_submodules`` controls the ``from package import module`` heuristic;
    it needs the packages to be importable on the machine doing the scan, so turn
    it off when cross-building.
    """
    local = set(local_modules)
    excludes = tuple(exclude_prefixes)
    names: set[str] = set()

    for path in sorted(Path(root).rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    names.add(alias.name)
            elif isinstance(node, ast.ImportFrom):
                # level > 0 is a relative import: it stays inside the package.
                if node.level or not node.module:
                    continue
                names.add(node.module)
                if not resolve_submodules:
                    continue
                for alias in node.names:
                    if alias.name == "*":
                        continue
                    full = node.module + "." + alias.name
                    if _submodule_exists(full):
                        names.add(full)

    return sorted(
        n for n in names
        if n.split(".")[0] not in local and not _is_excluded(n, excludes)
    )


def render(names: Iterable[str]) -> str:
    """Render the generated module source."""
    body = "".join(f"import {name}  # noqa: F401\n" for name in names)
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="pyi_deps", description="Scan a staged tree and emit a PyInstaller deps module."
    )
    parser.add_argument("--root", required=True, help="directory to scan recursively")
    parser.add_argument("--out", required=True, help="path of the generated .py file")
    parser.add_argument("--local", action="append", default=[],
                        help="local module name to ignore (repeatable)")
    parser.add_argument("--exclude", action="append", default=[],
                        help="import prefix to exclude, e.g. PIL (repeatable)")
    parser.add_argument("--no-submodules", action="store_true",
                        help="skip the 'from package import module' resolution")
    args = parser.parse_args(argv)

    names = scan(args.root, local_modules=args.local, exclude_prefixes=args.exclude,
                 resolve_submodules=not args.no_submodules)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    # Path.write_text(newline=...) only exists from 3.10; Path.open does the job on 3.9.
    with out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(names))
    print(f"pyi_deps: {len(names)} imports -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
