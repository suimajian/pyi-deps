from __future__ import annotations

import ast

from pyi_deps import main, render, scan


def _tree(tmp_path, files: dict[str, str]):
    for name, src in files.items():
        p = tmp_path / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(src, encoding="utf-8")
    return tmp_path


def test_collects_plain_and_from_imports(tmp_path):
    root = _tree(tmp_path, {
        "a.py": "import os\nimport requests\nfrom bs4 import BeautifulSoup\n",
    })
    names = scan(root, local_modules=(), resolve_submodules=False)
    assert "requests" in names and "bs4" in names
    assert "os" not in names, "standard library is filtered out by default"


def test_drops_local_modules(tmp_path):
    root = _tree(tmp_path, {
        "app.py": "import requests\nimport config\n",
        "config.py": "X = 1\n",
    })
    names = scan(root, local_modules={"config"})
    assert "requests" in names
    assert "config" not in names


def test_prefix_exclusion_matches_package_tree(tmp_path):
    root = _tree(tmp_path, {"a.py": "import PIL\nimport PIL.Image\nimport numpy\n"})
    names = scan(root, exclude_prefixes=("PIL",))
    assert names == ["numpy"]


def test_relative_imports_are_ignored(tmp_path):
    root = _tree(tmp_path, {"pkg/a.py": "from .b import thing\nfrom .. import c\n"})
    assert scan(root) == []


def test_recurses_into_subdirectories_and_skips_pycache(tmp_path):
    root = _tree(tmp_path, {
        "top.py": "import top_level\n",
        "pkg/deep/mod.py": "import deep_mod\n",
        "__pycache__/junk.py": "import should_not_appear\n",
    })
    names = scan(root)
    assert "top_level" in names and "deep_mod" in names
    assert "should_not_appear" not in names


def test_resolves_from_package_import_module(tmp_path):
    root = _tree(tmp_path, {"a.py": "from json import decoder\n"})
    names = scan(root, resolve_submodules=True, include_stdlib=True)
    assert "json" in names
    assert "json.decoder" in names

    names_no_resolve = scan(root, resolve_submodules=False, include_stdlib=True)
    assert "json.decoder" not in names_no_resolve


def test_include_stdlib_keeps_standard_library(tmp_path):
    root = _tree(tmp_path, {"a.py": "import os\nimport requests\n"})
    assert scan(root, include_stdlib=True) == ["os", "requests"]


def test_output_is_sorted_and_unique(tmp_path):
    root = _tree(tmp_path, {
        "a.py": "import requests\nimport os\n",
        "b.py": "import requests\n",
    })
    names = scan(root)
    assert names == sorted(set(names))


def test_render_is_importable_and_commented():
    src = render(["os", "json"])
    assert "Generated by pyi_deps" in src
    assert "import os  # noqa: F401" in src
    compile(src, "<generated>", "exec")


def test_optional_import_does_not_break_the_generated_module(tmp_path):
    """`try: import x / except ImportError` must survive into the generated file.

    A bare `import x` would make a missing optional package abort startup, which is
    the exact failure this tool exists to prevent.
    """
    root = _tree(tmp_path, {
        "win.py": "try:\n    import win32api\nexcept ImportError:\n    win32api = None\n",
    })
    names = scan(root, resolve_submodules=False)
    assert "win32api" in names

    out = tmp_path / "_deps.py"
    assert main(["--root", str(root), "--out", str(out)]) == 0
    src = out.read_text(encoding="utf-8")
    assert "try:" in src and "except ImportError" in src

    # Import it in a fresh interpreter: the module must not raise.
    import subprocess
    import sys as _sys
    result = subprocess.run(
        [_sys.executable, "-c", "import importlib.util,sys;"
         "spec=importlib.util.spec_from_file_location('deps', sys.argv[1]);"
         "m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);print('ok')",
         str(out)],
        capture_output=True, text=True,
    )
    assert result.returncode == 0, result.stderr
    assert "ok" in result.stdout


def test_cli_writes_file(tmp_path, capsys):
    root = _tree(tmp_path, {"a.py": "import requests\n"})
    out = tmp_path / "build" / "_deps.py"
    rc = main(["--root", str(root), "--out", str(out)])
    assert rc == 0
    assert out.read_text(encoding="utf-8").startswith("# Generated by pyi_deps")
    assert "import requests" in out.read_text(encoding="utf-8")
    assert "1 imports" in capsys.readouterr().out


def test_cli_accepts_local_and_exclude(tmp_path):
    root = _tree(tmp_path, {"a.py": "import app\nimport PIL\nimport requests\n"})
    out = tmp_path / "_deps.py"
    assert main(["--root", str(root), "--out", str(out), "--local", "app",
                 "--exclude", "PIL"]) == 0
    text = out.read_text(encoding="utf-8")
    assert "import requests" in text
    assert "import app" not in text
    assert "import PIL" not in text


def test_syntax_error_in_source_propagates(tmp_path):
    root = _tree(tmp_path, {"bad.py": "def broken(:\n"})
    try:
        scan(root)
    except SyntaxError:
        pass
    else:
        raise AssertionError("scan() should surface a SyntaxError, not skip the file")
